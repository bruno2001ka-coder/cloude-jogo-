import fs from'node:fs';
import{FAZENDA_CONFIG as F}from'../src/FarmConfig.js';

const wg=fs.readFileSync(new URL('../src/WorldGenerator.js',import.meta.url),'utf8');
const cam=fs.readFileSync(new URL('../src/Camera.js',import.meta.url),'utf8');
const phys=fs.readFileSync(new URL('../src/Physics.js',import.meta.url),'utf8');
const player=fs.readFileSync(new URL('../src/Player.js',import.meta.url),'utf8');
const C=F.casa,checks=[];
const box=(nome,cx,cz,w,d)=>({nome,cx,cz,w,d,minX:cx-w/2,maxX:cx+w/2,minZ:cz-d/2,maxZ:cz+d/2});
const gap=(a,b)=>Math.hypot(Math.max(0,b.minX-a.maxX,a.minX-b.maxX),Math.max(0,b.minZ-a.maxZ,a.minZ-b.maxZ));
const overlap=(a,b)=>Math.min(a.maxX,b.maxX)>Math.max(a.minX,b.minX)&&Math.min(a.maxZ,b.maxZ)>Math.max(a.minZ,b.minZ);
const dPoint=(x,z,b)=>Math.hypot(Math.max(b.minX-x,0,x-b.maxX),Math.max(b.minZ-z,0,z-b.maxZ));
const dSeg=(a,b,r)=>{let m=Infinity;for(let i=0;i<=240;i++){const t=i/240;m=Math.min(m,dPoint(a.x+(b.x-a.x)*t,a.z+(b.z-a.z)*t,r));}return m};
const dRota=r=>Math.min(dSeg(F.acesso.a,F.acesso.via,r),dSeg(F.acesso.via,F.acesso.b,r));
const ok=(id,nome,cond,det={})=>{if(!cond)throw new Error('[AUDIT '+id+'] '+nome+' '+JSON.stringify(det));checks.push({id,nome,...det})};

const casa=box('casa',C.x,C.z,C.largura,C.profundidade);
const fund=box('fundacao',C.x,C.z,C.baseLargura,C.baseProfundidade);
const varanda=box('varanda',C.x,C.z+2.95,6.8,1.35);
const deg1=box('degrau1',C.x,C.z+3.17,2.8,.46),deg2=box('degrau2',C.x,C.z+3.42,2.25,.34);
const pano=(C.largura-C.portaVao)/2,centro=C.portaVao/2+pano/2,janelas=[C.x-centro,C.x+centro];
const currais=Object.values(F.currais).map(q=>box('curral-'+q.tipo,q.cx,q.cz,q.w,q.d));
const cultivo=box('cultivo',(F.cultivo.minX+F.cultivo.maxX)/2,(F.cultivo.minZ+F.cultivo.maxZ)/2,F.cultivo.maxX-F.cultivo.minX,F.cultivo.maxZ-F.cultivo.minZ);
const cocho=box('cocho',F.servico.cocho.x,F.servico.cocho.z,F.servico.cocho.largura,F.servico.cocho.profundidade);
const barril=box('barril',F.servico.barril.x,F.servico.barril.z,F.servico.barril.raio*2,F.servico.barril.raio*2);
const polo=box('polo',F.polo.x,F.polo.z,.8,.8);
const caixa=box('caixa',F.cx+9.5,F.cz-9.5,1.6,1.6),moinho=box('moinho',F.cx+7.2,F.cz-9.2,.6,.6);
const porteira=box('porteira',F.porteira.x,F.porteira.z,.3,F.porteira.vao);
const limite=box('limite',F.cx,F.cz,F.meiaLarg*2,F.meiaProf*2);
const f={};

ok(1,'dimensoes casa',C.largura===6&&C.profundidade===5&&C.altura===3.2);
ok(2,'centro casa',C.x===-94&&C.z===-56);
ok(3,'fundacao',C.baseLargura>=C.largura&&C.baseProfundidade>=C.profundidade);
ok(4,'paredes',wg.includes('paredeFrenteE')&&wg.includes('paredeFrenteD'));
ok(5,'telhado',wg.includes('Math.hypot(meiaLargC,subidaTelhado)+beiral'));
ok(6,'varanda',overlap(varanda,casa)&&varanda.w===6.8&&varanda.d===1.35);
ok(7,'degraus',overlap(deg1,varanda)&&gap(deg1,deg2)===0);
ok(8,'porta',C.portaVao===2.35&&C.portaFrenteZ===C.z+2.53);
ok(9,'janelas',Math.abs(janelas[0]+96.0875)<1e-9&&Math.abs(janelas[1]+91.9125)<1e-9,{janelas});
ok(10,'calhas',wg.includes('bz-3.02,bz+3.02'));
ok(11,'forro',wg.includes('BoxGeometry(5.72,.08,4.72)')&&wg.includes('by+3.08'));
ok(12,'pilares',wg.includes('[-2.85,2.85]')&&2.85>C.portaVao/2+.8);
for(const q of currais)f[q.nome]=gap(fund,q);
ok(13,'vacas',f['curral-vaca']>=1.8,{m:+f['curral-vaca'].toFixed(2)});
ok(14,'porcos',f['curral-porco']>=5,{m:+f['curral-porco'].toFixed(2)});
ok(15,'galinhas',f['curral-galinha']>=10,{m:+f['curral-galinha'].toFixed(2)});
f.cultivo=gap(fund,cultivo);ok(16,'plantacao',f.cultivo>=4.3,{m:+f.cultivo.toFixed(2)});
const borda=Math.min(fund.minX-limite.minX,limite.maxX-fund.maxX,fund.minZ-limite.minZ,limite.maxZ-fund.maxZ);
ok(17,'cerca',borda>=1.8,{m:+borda.toFixed(2)});
ok(18,'cocho',gap(fund,cocho)>0);
ok(19,'barril',gap(fund,barril)>0);
ok(20,'polo servico',gap(fund,polo)>.8&&!overlap(polo,barril)&&!overlap(polo,cocho)&&currais.every(q=>!overlap(polo,q)),{x:F.polo.x,z:F.polo.z});
ok(21,'caixa dagua',gap(fund,caixa)>8&&currais.every(q=>!overlap(caixa,q)));
ok(22,'moinho',gap(fund,moinho)>8&&currais.every(q=>!overlap(moinho,q)));
ok(23,'porteira',F.porteira.x===F.cx+F.meiaLarg&&gap(fund,porteira)>15);
const bloqueios=[...currais,cultivo,cocho,barril,caixa,moinho].filter(o=>dRota(o)<.55);
ok(24,'corredor entrada',bloqueios.length===0,{bloqueios:bloqueios.map(x=>x.nome)});
ok(25,'circulacao jogador',C.portaVao>=1.8&&borda>=1.8&&wg.includes('superficiesAndaveis.push(pisoVaranda)'));
ok(26,'camera anti clipping',phys.includes('obstaculosCamera')&&cam.includes('LISTAS_BLOQUEIO_CAMERA')&&wg.includes('registrarObstaculoCamera(agua)')&&wg.includes('registrarObstaculoCamera(telheiroVaranda)'));
ok(27,'anti travamento',player.includes('destravarJogador')&&player.includes('vigiarTravamento'));
ok(28,'sem flutuacao externa',wg.includes('g.position.set(x,obterElevacao(x,z),z)')&&wg.includes('obterElevacao(cocho.x,cocho.z)+.3'));
ok(29,'canteiros apoiados',wg.includes('obterElevacao(mx,mz)+.02'));
const externos=[...currais,cultivo,caixa,moinho],acidentes=[];
for(let i=0;i<externos.length;i++)for(let j=i+1;j<externos.length;j++)if(overlap(externos[i],externos[j]))acidentes.push([externos[i].nome,externos[j].nome]);
ok(30,'sobreposicoes acidentais',acidentes.length===0,{acidentes});

console.log(JSON.stringify({ok:true,total:checks.length,checks,folgas:f},null,2));
